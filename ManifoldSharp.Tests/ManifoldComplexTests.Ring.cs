		/// <summary>
		/// C++ TEST(BooleanComplex, Ring) — subtraction of two near-coincident ring
		/// segments must succeed.
		/// </summary>
		/// <returns>A task representing the test.</returns>
		[Test]
		public async Task CppRing()
		{
			Manifold arg0 = Manifold.FromMeshGL(RingMesh(0));
			Manifold arg1 = Manifold.FromMeshGL(RingMesh(1));
			Manifold result = arg0.Clone() - arg1.Clone();
			await Assert.That(arg0.Status()).IsEqualTo(Error.NoError).Because("arg0 status");
			await Assert.That(arg1.Status()).IsEqualTo(Error.NoError).Because("arg1 status");
			await Assert.That(result.Status()).IsEqualTo(Error.NoError).Because("result status");
		}

		/// <summary>
		/// Build mgl_0 / mgl_1 for the Ring test — the port of complex.rs's
		/// <c>ring_mesh(src, occurrence)</c>, reading the transcribed arrays instead of
		/// the C++ source.
		/// </summary>
		/// <param name="occurrence">0 for mgl_0, 1 for mgl_1.</param>
		/// <returns>The mesh.</returns>
		private static MeshGL RingMesh(int occurrence)
		{
			MeshGL m = new MeshGL();
			m.NumProp = 3;
			m.VertProperties = new List<float>(
				occurrence == 0 ? Ring0VertProperties : Ring1VertProperties);
			m.TriVerts = new List<uint>(occurrence == 0 ? Ring0TriVerts : Ring1TriVerts);
			m.RunIndex = new List<uint>(occurrence == 0 ? Ring0RunIndex : Ring1RunIndex);
			m.RunOriginalId = new List<uint>(
				occurrence == 0 ? Ring0RunOriginalId : Ring1RunOriginalId);
			m.FaceId = new List<uint>(occurrence == 0 ? Ring0FaceId : Ring1FaceId);
			return m;
		}

