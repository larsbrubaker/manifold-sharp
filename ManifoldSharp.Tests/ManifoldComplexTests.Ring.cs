// Test 24 of src/manifold_tests/complex.rs — BooleanComplex.Ring — together with
// the two meshes it consumes.
//
// ── Provenance of the data ───────────────────────────────────────────────────
// As with InterpolatedNormals, the Rust reads these out of the pinned C++ test
// source at test time (`ring_mesh(&src, occurrence)` over
// `read_cpp_test_source("boolean_complex_test.cpp")`), and this port transcribes
// them instead — CLAUDE.md, "Verification nets" #1. Source:
//
//   manifold/test/boolean_complex_test.cpp, the `mgl_0()` and `mgl_1()` mesh
//   factories at lines 857–1444 of commit
//   11235e6b8ebea2dbed8aec4285685aafd3d95667 (elalish/manifold v3.5.2), the
//   commit manifold-rust pins its `cpp-reference/manifold` submodule to.
//   `occurrence` 0 is mgl_0, 1 is mgl_1 — the same indexing `ring_mesh` uses.
//
// Transcribed mechanically by the same parse `cpp_inline_array` performs, then
// verified token-for-token against the C++. As in
// ManifoldComplexTests.InterpolatedNormals.cs, each float is the shortest
// decimal that round-trips to the exact f32 the Rust's `as f32` produces; see
// that file's header for why the spellings differ from the C++ text.
//
// ── One C++ construct with no analog ─────────────────────────────────────────
// The C++ test sets `ManifoldParams().processOverlaps = true`, which only
// silences a MANIFOLD_DEBUG-only assertion. There is no behavioral analog in the
// Rust and none here, so the port asserts exactly what the Rust asserts: all
// three statuses are NoError.

